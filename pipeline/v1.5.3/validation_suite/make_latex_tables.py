"""Manuscript tables (LaTeX, fully enclosed grids, no booktabs) generated from
the v1.5.2 audit results, so no number is retyped by hand.
Usage: make_latex_tables.py XVAL_JSON XVAL_V131_JSON SUMMARY_V152_CSV S2A_CSV OUT_TEX"""
import sys, json, math
import pandas as pd

xv, xv131, summ, s2a, out = sys.argv[1:6]
X = json.load(open(xv))["satellites"]
X131 = json.load(open(xv131))["satellites"]
S = pd.read_csv(summ)
A = pd.read_csv(s2a)
ST = {"SUPPORTED": "S", "NOT SUPPORTED": "N", "NOT EVALUABLE": "NE", "NOT RUN": "NR"}


def n(v, d=0):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "--"
    return f"{v:,.{d}f}".replace(",", "{,}")


def sgn(v, d=3):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "--"
    return ("$-$" if v < 0 else "") + f"{abs(v):.{d}f}"


L = []
w = L.append
w(r"""% =============================================================================
% ARF v1.5.2 audit: manuscript tables (generated by make_latex_tables.py from
% the audit results; do not edit numbers by hand). Fully enclosed grids
% (vertical bars and \hline), no booktabs. Single 48 h window of
% 12-14 October 2026: exploratory, not the confirmatory protocol's results.
% Compile test: pdflatex arf_tables_v152.tex (standalone wrapper below). For
% IEEEtran, paste the table* environments between the markers.
% =============================================================================
\documentclass[twocolumn]{article}
\usepackage[paperwidth=8.5in,paperheight=11in,textwidth=7.16in,columnsep=0.16in,top=0.75in,bottom=1in]{geometry}
\usepackage{array}
\usepackage{multirow}
\newcolumntype{L}[1]{>{\raggedright\arraybackslash}m{#1}}
\newcolumntype{C}[1]{>{\centering\arraybackslash}m{#1}}
\newcolumntype{R}[1]{>{\raggedleft\arraybackslash}m{#1}}
\begin{document}
% Needs (preamble): \usepackage{array,multirow} and the three column types
% L, C, R defined above (\newcolumntype, array package).
% ----- paste from here -------------------------------------------------------
""")

# Table A: independent SGP4 check of Cells 2, 4 and 5
w(r"""\begin{table*}[!t]
\centering
\caption{Independent check of the access and refinement stages (Cells 2, 4 and 5) against a separate SGP4
propagation: CKGR and Okavango region, open-data satellites, 48 h window from 12 October 2026 08:27 UTC.
Missing: tiles clearly inside the swath and sunlit at the independent closest approach but absent from the ARF
output; spurious: ARF tiles clearly outside the swath or below the sun limit (tolerance 0.02$^\circ$ on the
swath edge and 0.5$^\circ$ on the sun limit). $|\Delta\theta|$: off-nadir angle at closest approach. Last
column: tile passes counted in two consecutive one-minute strips by the strip rule of release 1.3.1 and by
that of release 1.5.2. Sentinel-2C passed near the region four times in the window with no tile in view, in both
computations.}
\label{tab:arf_xval_sgp4}
\renewcommand{\arraystretch}{1.25}
\setlength{\tabcolsep}{4pt}
\footnotesize
\begin{tabular}{|L{1.9cm}|R{1.45cm}|R{1.6cm}|R{1.3cm}|R{1.35cm}|R{1.5cm}|R{1.5cm}|R{1.6cm}|C{1.9cm}|}
\hline
\textbf{Satellite} & \textbf{Tile passes (ARF)} & \textbf{Clearly in view (indep.)} & \textbf{Missing} &
\textbf{Spurious} & \textbf{Max $|\Delta\theta|$ ($^\circ$)} & \textbf{P99 $|\Delta\theta|$ ($^\circ$)} &
\textbf{Max $|\Delta$sun$|$ ($^\circ$)} & \textbf{In two strips (1.3.1 / 1.5.2)} \\
\hline""")
for sat in ("LANDSAT 8", "LANDSAT 9", "SENTINEL-2A", "SENTINEL-2B", "SENTINEL-2C"):
    r, r0 = X[sat], X131[sat]
    name = sat.title().replace("Sentinel-2a", "Sentinel-2A").replace("Sentinel-2b", "Sentinel-2B") \
        .replace("Sentinel-2c", "Sentinel-2C")
    if r.get("tiles_in_view") == 0:
        w(rf"{name} & 0 & 0 & -- & -- & -- & -- & -- & -- \\ \hline")
        continue
    w(rf"{name} & {n(r['refined_tile_passes'])} & {n(r['independent_in_fov_sunlit'])} & "
      rf"{r['missing_from_refined']} & {r['false_positives']} & {r['angle_abs_diff_deg_max']:.4f} & "
      rf"{r['angle_abs_diff_deg_p99']:.4f} & {r['sun_abs_diff_deg_max']:.2f} & "
      rf"{n(r0['tile_passes_in_two_strips'])} / {n(r['tile_passes_in_two_strips'])} \\ \hline")
w(r"""\end{tabular}
\end{table*}
""")

# Table B: Sentinel-2A sensitivity, CKGR + Okavango
w(r"""\begin{table*}[!t]
\centering
\caption{Sensitivity to Sentinel-2A, which is tracked but operates under an extension-campaign acquisition plan
(in the Earth Search catalogue it imaged this region every 20 days in August--October 2026): CKGR and Okavango
region, release 1.5.2, single 48 h window from 12 October 2026 (exploratory). ECC:
earliest-completion cover; FCFS: first come, first served; images: median over onsets to reach 95\% of
reachable tiles. H2: mean coverage gain of the adaptive (Fail-Signal) selector over the open-loop plan with the
same images, in percentage points, with its one-sided 95\% lower bound (LB). Open: Landsat 8/9 and
Sentinel-2A/B/C; PS: PlanetScope (cons.: 3.0$^\circ$ field of view; opt.: 4.0$^\circ$). S: supported; N: not
supported; NE: not evaluable.}
\label{tab:arf_s2a_sensitivity}
\renewcommand{\arraystretch}{1.25}
\setlength{\tabcolsep}{4pt}
\footnotesize
\begin{tabular}{|L{2.7cm}|C{1.3cm}|R{1.3cm}|R{1.6cm}|C{1.5cm}|C{0.8cm}|R{1.1cm}|C{0.8cm}|C{2.1cm}|C{0.8cm}|C{0.8cm}|}
\hline
\textbf{Fleet} & \textbf{S2A} & \textbf{Tile obs.} & \textbf{Reachable (\%)} &
\textbf{Images ECC / FCFS} & \textbf{H1a} & \textbf{H1b (\%)} & \textbf{H1b} & \textbf{H2 (LB)} &
\textbf{H2} & \textbf{H3} \\
\hline""")
names = {"open data + PlanetScope (conservative)": "Open + PS (cons.)$^{\\ast}$",
         "open data + PlanetScope (optimistic)": "Open + PS (opt.)",
         "Landsat 8/9 + Sentinel-2": "Open data"}
for fl in ("open data + PlanetScope (conservative)", "open data + PlanetScope (optimistic)", "Landsat 8/9 + Sentinel-2"):
    r = A[(A.ROI == "CKGR + Okavango") & (A.Fleet == fl)].iloc[0]
    for k, (lab, suf) in enumerate((("included", " with S2A"), ("left out", " without S2A"))):
        first = (rf"\multirow{{2}}{{=}}{{{names[fl]}}}" if k == 0 else "")
        imgs = f"{n(r['Median images to level, ECC' + suf])} / {n(r['Median images to level, FCFS' + suf])}"
        h2 = f"{sgn(r['H2 mean difference (coverage points)' + suf])} ({sgn(r['H2 one-sided 95% lower bound' + suf])})"
        st = (f"{ST[r['H2 status (time-aware; adaptive vs open-loop, same images)' + suf]]} & "
              f"{ST[r['H3 status' + suf]]}")
        w(rf"{first} & {lab} & {n(r['Refined rows' + suf])} & {n(r['Reachable usable tiles, clear (%)' + suf], 1)} & "
          rf"{imgs} & {ST[r['H1a status (ECC)' + suf]]} & {n(r['H1b ECC fewer images within margin (%)' + suf], 1)} & "
          rf"{ST[r['H1b status' + suf]]} & {h2} & {st} \\ " + (r"\cline{2-11}" if k == 0 else r"\hline"))
w(r"""\multicolumn{11}{|l|}{$^{\ast}$Primary design of the confirmatory protocol.} \\
\hline
\end{tabular}
\end{table*}
""")

# Table C: the 15 runs under release 1.5.2
w(r"""\begin{table*}[!t]
\centering
\caption{The 15 region and fleet runs of 12 October 2026 under release 1.5.2 (Cells 6--8 on the corrected
Cell 5 output; single 48 h window, exploratory). H1a: share of onsets at which ECC reaches 95\% of reachable
tiles within one orbital period of the physical floor, with its one-sided 95\% Clopper--Pearson lower bound;
H1b: share of eligible onsets at which ECC does so with fewer images than FCFS. Abbreviations as in
Table~\ref{tab:arf_s2a_sensitivity}.}
\label{tab:arf_runs_v152}
\renewcommand{\arraystretch}{1.2}
\setlength{\tabcolsep}{3.5pt}
\footnotesize
\begin{tabular}{|L{1.4cm}|L{2.5cm}|R{1.1cm}|R{1.6cm}|C{1.8cm}|C{0.7cm}|C{1.8cm}|C{0.7cm}|C{2.15cm}|C{0.7cm}|C{0.7cm}|}
\hline
\textbf{Region} & \textbf{Fleet} & \textbf{Tile obs.} & \textbf{Reachable (\%)} & \textbf{H1a (\%) [LB]} &
\textbf{H1a} & \textbf{H1b (\%) [LB]} & \textbf{H1b} & \textbf{H2 (LB)} & \textbf{H2} & \textbf{H3} \\
\hline""")
reg = {"CKGR + Okavango": "CKGR + Okavango", "Karoo NR": "Karoo NR", "Lower Zambezi NP": "Lower Zambezi NP"}
fl_short = {"Landsat 8/9 + Sentinel-2": "Open data", "open data + PlanetScope (conservative)": "Open + PS (cons.)",
            "open data + PlanetScope (optimistic)": "Open + PS (opt.)", "PlanetScope (conservative)": "PS (cons.)",
            "PlanetScope (optimistic)": "PS (opt.)"}
for roi in ("CKGR + Okavango", "Lower Zambezi NP", "Karoo NR"):
    sub = S[S.ROI == roi]
    order = ["open data + PlanetScope (conservative)", "open data + PlanetScope (optimistic)",
             "Landsat 8/9 + Sentinel-2", "PlanetScope (conservative)", "PlanetScope (optimistic)"]
    for i, fl in enumerate(order):
        r = sub[sub.Fleet == fl].iloc[0]
        first = rf"\multirow{{5}}{{=}}{{{reg[roi]}}}" if i == 0 else ""
        h1a = f"{n(r['H1a ECC within margin (%)'], 1)} [{n(r['H1a ECC 95% lower bound (%)'], 1)}]"
        h1b = (f"{n(r['H1b ECC fewer images within margin (%)'], 1)} [{n(r['H1b 95% lower bound (%)'], 1)}]"
               if not pd.isna(r['H1b ECC fewer images within margin (%)']) else "--")
        h2 = f"{sgn(r['H2 mean difference (coverage points)'])} ({sgn(r['H2 one-sided 95% lower bound'])})"
        w(rf"{first} & {fl_short[fl]} & {n(r['Refined rows'])} & {n(r['Reachable usable tiles, clear (%)'], 1)} & "
          rf"{h1a} & {ST[r['H1a status (ECC)']]} & {h1b} & {ST[r['H1b status']]} & {h2} & "
          rf"{ST[r['H2 status (time-aware; adaptive vs open-loop, same images)']]} & {ST[r['H3 status']]} \\ "
          + (r"\cline{2-11}" if i < 4 else r"\hline"))
w(r"""\multicolumn{11}{|l|}{Open: Landsat 8/9 and Sentinel-2A/B/C; PS: PlanetScope (cons.: 3.0$^\circ$ field
of view, PS2.SD; opt.: 4.0$^\circ$, PSB.SD).} \\
\hline
\end{tabular}
\end{table*}
% ----- to here ----------------------------------------------------------------
\end{document}
""")
open(out, "w").write("\n".join(L))
print("written", out)
